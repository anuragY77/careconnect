CREATE TABLE icd10_code (
    code        VARCHAR(10)  PRIMARY KEY,
    description VARCHAR(200) NOT NULL,

    CONSTRAINT ck_icd10_code_format CHECK (code ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$'),
    CONSTRAINT ck_icd10_code_description CHECK (btrim(description) <> '')
);

